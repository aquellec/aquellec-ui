/*
  FRONT PAGE — the single source of truth for @aquellec/ui.

  The sentence that explains nearly every value below:

    A hiring decision is the lead story of somebody's year. Set it like one.
    Black ink, white stock, one signal colour, and type that knows which line
    matters most.

  It resolves a real tension. Welcome to the Jungle is editorial, human and
  unafraid of colour; Uber is stark, enormous and disciplined. A tool that
  decides who gets an interview needs both — warmth so a candidate hands over
  their story, and hierarchy so a recruiter can see the verdict from across the
  room. A newspaper front page has always done exactly that, and it does it
  without a single card: rules, columns, whitespace and a headline that dwarfs
  the body.

  Everything downstream is a rendering of this file: `src/tailwind-preset.ts`
  for Tailwind 3, `dist/theme.css` for Tailwind 4 (generated by
  `scripts/generate-theme-css.mjs`), and the Tokens documentation page. Change a
  value here and all three follow. Nothing may be hard-coded anywhere else.

  Every foreground/background pair below was measured, not estimated. Text pairs
  clear WCAG 2.1 AA (4.5:1); borders, focus rings and data marks clear the 3:1
  required of non-text UI (1.4.11), in light *and* dark. The palette is high
  contrast by design, which makes that floor a starting point rather than a
  ceiling.
*/

