/**
 * One curve, four durations.
 *
 * `settle` leaves immediately and arrives slowly: the interface answers the
 * moment you act, then comes to rest. A symmetric ease makes a control feel
 * like it is thinking before it responds, which is the opposite of what a tool
 * used all day should feel like.
 *
 * The durations are spelled in components with Tailwind's numeric utilities
 * (`duration-150`), which resolve to identical milliseconds under Tailwind 3
 * and 4 — a named duration scale does not, and this package supports both
 * majors. The values are recorded here so the documentation, and any consumer
 * writing plain CSS, read them from the same place.
 *
 * `prefers-reduced-motion` collapses all of it; the reset ships in the preset.
 */
export const aquellecMotion = {
  easing: {
    /** The signature curve. Immediate exit, unhurried arrival. */
    settle: 'cubic-bezier(0.2, 0, 0, 1)',
  },
  duration: {
    /** Colour and border changes under the pointer. */
    fast: '100ms',
    /** The default: state changes on a control. */
    base: '150ms',
    /** Surfaces entering or leaving — dialogs, toasts, drawers. */
    slow: '300ms',
    /** Data settling into place — a gauge sweep, a bar filling. */
    data: '700ms',
  },
} as const;

export type AquellecMotion = typeof aquellecMotion;

